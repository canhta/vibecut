//! The stable [`Text`] key table with its English and Vietnamese rows.

use super::Locale;

macro_rules! catalog {
    ($(
        $variant:ident {
            key: $key:literal,
            en: $en:literal,
            vi: $vi:literal $(,)?
        }
    ),* $(,)?) => {
        /// Stable message keys. The enum keeps every call site compiler-checked.
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
        pub enum Text {
            $($variant),*
        }
        impl Text {
            pub const ALL: &'static [Self] = &[$(Self::$variant),*];
            pub const fn key(self) -> &'static str {
                match self { $(Self::$variant => $key),* }
            }
            pub const fn text(self, locale: Locale) -> &'static str {
                match locale {
                    Locale::En => match self { $(Self::$variant => $en),* },
                    Locale::Vi => match self { $(Self::$variant => $vi),* },
                }
            }
        }
    };
}


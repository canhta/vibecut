/// The palette colour at `index`, if any.
pub fn solid(index: usize) -> Option<Color> {
    SOLID.get(index).map(|value| {
        Color([
            ((value >> 16) & 0xff) as u8,
            ((value >> 8) & 0xff) as u8,
            (value & 0xff) as u8,
            255,
        ])
    })
}
